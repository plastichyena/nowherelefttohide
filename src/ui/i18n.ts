const TABLES: Record<Locale, TranslationTable> = { ja: JA, en: EN };

export function createTranslator(locale: Locale): (key: string, fallback?: string) => string {
  return (key, fallback = key) => TABLES[locale][key] ?? fallback;
}

export function getInitialLocale(): Locale {
  try {
    const saved = globalThis.localStorage?.getItem('nowhere-left-to-hide:locale');
    if (saved === 'en' || saved === 'ja') return saved;
  } catch {
    // Privacy mode can reject localStorage; Japanese is the required default.
  }
  return 'ja';
}

export function persistLocale(locale: Locale): void {
  try {
    globalThis.localStorage?.setItem('nowhere-left-to-hide:locale', locale);
  } catch {
    // Locale is a convenience preference, not a game-state mutation.
  }
}

export function toggleLocale(locale: Locale): Locale {
  return locale === 'ja' ? 'en' : 'ja';
}
